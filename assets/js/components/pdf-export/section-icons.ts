/** The default icon size in pixels. `PDFSvg` scales it to page points. */
const DEFAULT_ICON_SIZE = 20;

/**
 * Builds a section icon component from inlined SVG children.
 *
 * @since 1.182.0
 *
 * @param renderChildren Receives the resolved fill color, returns the SVG children.
 * @return Section icon component.
 */
function makeIcon( renderChildren: ( color: string ) => ReactNode ): PDFIcon {
	return function Icon( { size = DEFAULT_ICON_SIZE, color } ) {
		return createElement(
			PDFSvg,
			{
				width: size,
				height: size,
				viewBox: '0 0 20 20',
			},
			renderChildren( color ?? PDF_COLORS.SURFACES_ON_SURFACE )
		);
	};
}

