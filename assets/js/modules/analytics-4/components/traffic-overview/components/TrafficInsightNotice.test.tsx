/**
 * Internal dependencies
 */
import { render } from '@tests/js/test-utils';
import TrafficInsightNotice from './TrafficInsightNotice';

describe( 'TrafficInsightNotice', () => {
	it( 'should render the insight, with the names it highlights in bold and marked as generated by AI', () => {
		const { container, getByText } = render(
			<TrafficInsightNotice text="Your traffic from **substack.com** is 8% higher than your typical range" />
		);

		expect(
			container.querySelector(
				'.googlesitekit-traffic-overview__traffic-insight'
			)
		).toHaveTextContent(
			'AI-generatedYour traffic from substack.com is 8% higher than your typical range'
		);
		expect( getByText( 'substack.com' ).tagName ).toBe( 'STRONG' );
	} );

	it( 'should render a placeholder in place of the insight while it loads', () => {
		const { container } = render(
			<TrafficInsightNotice
				text="Your traffic is within your typical range"
				loading
			/>
		);

		expect(
			container.querySelector(
				'.googlesitekit-traffic-overview__traffic-insight .googlesitekit-preview-block'
			)
		).toBeInTheDocument();
		expect( container ).not.toHaveTextContent(
			'Your traffic is within your typical range'
		);
	} );

	it( 'should keep the same polite live region from the placeholder to the insight, so a screen reader reads the insight out once it arrives', () => {
		const { container, rerender } = render(
			<TrafficInsightNotice loading />
		);

		const liveRegion = container.querySelector(
			'.googlesitekit-traffic-overview__traffic-insight'
		);

		expect( liveRegion ).toHaveAttribute( 'aria-live', 'polite' );

		rerender(
			<TrafficInsightNotice text="Your traffic is within your typical range" />
		);

		// A live region announces a change to its content, not a region that
		// replaces it, so the insight arrives in the same element.
		expect(
			container.querySelector(
				'.googlesitekit-traffic-overview__traffic-insight'
			)
		).toBe( liveRegion );
		expect( liveRegion ).toHaveAttribute( 'aria-live', 'polite' );
		expect( liveRegion ).toHaveTextContent(
			'Your traffic is within your typical range'
		);
	} );

	it.each( [
		[ 'null', null ],
		[ 'an empty string', '' ],
	] )( 'should render nothing when the insight is %s', ( _, text ) => {
		const { container } = render( <TrafficInsightNotice text={ text } /> );

		expect( container ).toBeEmptyDOMElement();
	} );
} );
